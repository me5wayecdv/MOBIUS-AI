"""Content-addressed artefact storage with path and digest integrity checks.

Keyed by SHA-256 so re-uploading the same APK does not create a second copy. Files live
outside the repository because untrusted binaries do not belong in git and artefact storage
must remain separate from the database.
"""

from __future__ import annotations

import hashlib
import os
import re
import tempfile
from pathlib import Path

_KEY = re.compile(r"^apk/([0-9a-f]{2})/([0-9a-f]{64})\.apk$")


class ArtifactStore:
    def __init__(self, root: Path | str) -> None:
        self._root = Path(root).resolve()

    @property
    def root(self) -> Path:
        return self._root

    @staticmethod
    def digest(data: bytes) -> str:
        return hashlib.sha256(data).hexdigest()

    def key_for(self, sha256: str) -> str:
        if not re.fullmatch(r"[0-9a-f]{64}", sha256):
            raise ValueError("artifact digest must be a lowercase SHA-256 hex string")
        return f"apk/{sha256[:2]}/{sha256}.apk"

    def path_for(self, key: str) -> Path:
        """Resolve only the exact content-addressed key shape generated by this store."""
        match = _KEY.fullmatch(key)
        if match is None or match.group(1) != match.group(2)[:2]:
            raise ValueError(f"invalid content-addressed artefact key: {key!r}")
        target = self._root / key
        expected_parent = self._root / "apk" / match.group(1)
        if target.parent.resolve() != expected_parent.resolve():
            raise ValueError("artefact path escaped the configured storage root")
        if target.is_symlink():
            raise ValueError("artefact object must not be a symlink")
        return target

    def put(self, data: bytes, sha256: str | None = None) -> tuple[str, int]:
        """Atomically store bytes and verify the supplied digest, if any."""
        digest = sha256 or self.digest(data)
        if not re.fullmatch(r"[0-9a-f]{64}", digest):
            raise ValueError("artifact digest must be a lowercase SHA-256 hex string")
        if self.digest(data) != digest:
            raise ValueError("provided artifact digest does not match content")
        key = self.key_for(digest)
        target = self.path_for(key)
        target.parent.mkdir(parents=True, exist_ok=True)
        # Re-check after directory creation in case a concurrent filesystem actor replaced
        # a parent directory with a symlink between the initial validation and the write.
        if target.parent.resolve() != (self._root / "apk" / digest[:2]).resolve():
            raise ValueError("artefact directory escaped the configured storage root")
        if target.exists():
            if self.digest(target.read_bytes()) != digest:
                raise OSError("existing content-addressed artefact failed digest verification")
            return key, target.stat().st_size

        temp_path: str | None = None
        try:
            with tempfile.NamedTemporaryFile(
                mode="wb", dir=target.parent, prefix=".mobius-", delete=False
            ) as temp:
                temp_path = temp.name
                temp.write(data)
                temp.flush()
                os.fsync(temp.fileno())
            os.replace(temp_path, target)
            temp_path = None
        finally:
            if temp_path is not None:
                try:
                    os.unlink(temp_path)
                except FileNotFoundError:
                    pass
        return key, target.stat().st_size

    def get(self, key: str) -> bytes:
        target = self.path_for(key)
        data = target.read_bytes()
        digest = _KEY.fullmatch(key).group(2)  # path_for already validated the key
        if self.digest(data) != digest:
            raise OSError("stored artefact failed content digest verification")
        return data

    def exists(self, key: str) -> bool:
        target = self.path_for(key)
        return target.is_file() and not target.is_symlink()
