"""Content-addressed artefact storage.

Keyed by SHA-256 so re-uploading the same APK does not create a second copy, and so an
artefact's identity is provable rather than asserted. Files live outside the repository
(.gitignore covers data/ and *.apk) because a 50 MB hostile binary does not belong in git,
and because NFR-DATA-1 requires artefact storage to be separate from the database.

Local filesystem for now; the interface is the seam for S3-compatible storage later.
"""

from __future__ import annotations

import hashlib
from pathlib import Path


class ArtifactStore:
    def __init__(self, root: Path | str) -> None:
        self._root = Path(root)

    @property
    def root(self) -> Path:
        return self._root

    @staticmethod
    def digest(data: bytes) -> str:
        return hashlib.sha256(data).hexdigest()

    def key_for(self, sha256: str) -> str:
        return f"apk/{sha256[:2]}/{sha256}.apk"

    def path_for(self, key: str) -> Path:
        # Keys are generated by this class, never supplied by a client or a model. There
        # is no path where a caller-controlled string becomes a filesystem path.
        if ".." in Path(key).parts:
            raise ValueError(f"refusing traversal-shaped artefact key: {key!r}")
        return self._root / key

    def put(self, data: bytes, sha256: str | None = None) -> tuple[str, int]:
        """Store ``data`` and return ``(key, size)``. Idempotent by content."""
        digest = sha256 or self.digest(data)
        key = self.key_for(digest)
        target = self.path_for(key)
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists():
            target.write_bytes(data)
        return key, target.stat().st_size

    def get(self, key: str) -> bytes:
        return self.path_for(key).read_bytes()

    def exists(self, key: str) -> bool:
        return self.path_for(key).exists()
